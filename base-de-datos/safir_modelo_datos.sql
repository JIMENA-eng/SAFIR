    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capitulo_id  BIGINT       NOT NULL REFERENCES capitulo (id) ON DELETE CASCADE,
    version      INTEGER      NOT NULL CHECK (version > 0),
