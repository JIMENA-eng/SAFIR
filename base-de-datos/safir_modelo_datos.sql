CREATE DATABASE safir
    WITH ENCODING 'UTF8'
    TEMPLATE template0;

\connect safir

BEGIN;

CREATE TABLE genero (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE etiqueta (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE rol (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo             VARCHAR(254) NOT NULL,
    contrasena_hash    VARCHAR(100) NOT NULL,
    nombre_publico     VARCHAR(60)  NOT NULL,
    estado_cuenta      VARCHAR(12)  NOT NULL DEFAULT 'activa'
                       CHECK (estado_cuenta IN ('activa', 'suspendida', 'eliminada')),
    intentos_fallidos  SMALLINT     NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta    TIMESTAMPTZ,
    ultimo_acceso      TIMESTAMPTZ,
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ux_usuario_correo ON usuario (lower(correo));
CREATE UNIQUE INDEX ux_usuario_nombre_publico ON usuario (lower(nombre_publico));

CREATE TABLE usuario_rol (
    usuario_id   BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    rol_id       SMALLINT    NOT NULL REFERENCES rol (id),
    asignado_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE INDEX ix_usuario_rol_rol ON usuario_rol (rol_id);

CREATE TABLE perfil_usuario (
    usuario_id      BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    biografia       TEXT,
    avatar_ruta     VARCHAR(500),
    sitio_web       VARCHAR(255),
    actualizado_en  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sesion_token (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti          UUID        NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    usuario_id   BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    emitido_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    vence_en     TIMESTAMPTZ NOT NULL,
    revocado_en  TIMESTAMPTZ,
    ip           INET,
    agente       VARCHAR(300),
    CONSTRAINT ck_sesion_vigencia CHECK (vence_en > emitido_en)
);

CREATE INDEX ix_sesion_usuario ON sesion_token (usuario_id);
CREATE INDEX ix_sesion_vence ON sesion_token (vence_en);

CREATE TABLE obra (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id        BIGINT       NOT NULL REFERENCES usuario (id),
    genero_id       SMALLINT     NOT NULL REFERENCES genero (id),
    titulo          VARCHAR(100) NOT NULL CHECK (length(btrim(titulo)) > 0),
    descripcion     TEXT,
    portada_ruta    VARCHAR(500),
    clasificacion   VARCHAR(12)  NOT NULL DEFAULT 'todo_publico'
                    CHECK (clasificacion IN ('todo_publico', 'mayores_13', 'mayores_18')),
    avance          VARCHAR(10)  NOT NULL DEFAULT 'en_curso'
                    CHECK (avance IN ('en_curso', 'completa', 'pausada')),
    estado          VARCHAR(10)  NOT NULL DEFAULT 'borrador'
                    CHECK (estado IN ('borrador', 'publicada', 'archivada')),
    publicada_en    TIMESTAMPTZ,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_obra_publicada_en CHECK (estado = 'borrador' OR publicada_en IS NOT NULL)
);

CREATE INDEX ix_obra_autor         ON obra (autor_id);
CREATE INDEX ix_obra_estado_genero ON obra (estado, genero_id);
CREATE INDEX ix_obra_publicada_en  ON obra (publicada_en DESC) WHERE estado = 'publicada';

CREATE TABLE obra_etiqueta (
    obra_id      BIGINT  NOT NULL REFERENCES obra (id) ON DELETE CASCADE,
    etiqueta_id  INTEGER NOT NULL REFERENCES etiqueta (id),
    PRIMARY KEY (obra_id, etiqueta_id)
);

CREATE INDEX ix_obra_etiqueta_etiqueta ON obra_etiqueta (etiqueta_id);

CREATE TABLE obra_estadistica (
    obra_id            BIGINT PRIMARY KEY REFERENCES obra (id) ON DELETE CASCADE,
    total_lecturas     BIGINT  NOT NULL DEFAULT 0 CHECK (total_lecturas >= 0),
    total_valoraciones INTEGER NOT NULL DEFAULT 0 CHECK (total_valoraciones >= 0),
    suma_puntaje       BIGINT  NOT NULL DEFAULT 0 CHECK (suma_puntaje >= 0),
    total_seguidores   INTEGER NOT NULL DEFAULT 0 CHECK (total_seguidores >= 0),
    promedio           NUMERIC(3,2) GENERATED ALWAYS AS (
                           CASE WHEN total_valoraciones = 0 THEN 0
                                ELSE ROUND(suma_puntaje::NUMERIC / total_valoraciones, 2) END
                       ) STORED
);

CREATE TABLE importacion_pdf (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id               BIGINT       NOT NULL REFERENCES obra (id) ON DELETE CASCADE,
    autor_id              BIGINT       NOT NULL REFERENCES usuario (id),
    nombre_archivo        VARCHAR(255) NOT NULL,
    tamano_bytes          INTEGER      NOT NULL
                          CHECK (tamano_bytes > 0 AND tamano_bytes <= 20971520),
    hash_archivo          CHAR(64),
    archivo_ruta          VARCHAR(500),
    capitulos_detectados  INTEGER      NOT NULL DEFAULT 0 CHECK (capitulos_detectados >= 0),
    estado                VARCHAR(12)  NOT NULL DEFAULT 'en_revision'
                          CHECK (estado IN ('en_revision', 'confirmada', 'rechazada')),
    motivo_rechazo        TEXT,
    creado_en             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resuelto_en           TIMESTAMPTZ,
    CONSTRAINT ck_importacion_motivo
        CHECK (estado <> 'rechazada' OR motivo_rechazo IS NOT NULL),
    CONSTRAINT ck_importacion_resuelta
        CHECK (estado = 'en_revision' OR resuelto_en IS NOT NULL),
    CONSTRAINT ux_importacion_id_obra UNIQUE (id, obra_id)
);

CREATE INDEX ix_importacion_obra_estado ON importacion_pdf (obra_id, estado);
CREATE INDEX ix_importacion_autor       ON importacion_pdf (autor_id);

CREATE TABLE capitulo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id            BIGINT       NOT NULL REFERENCES obra (id) ON DELETE CASCADE,
    importacion_id     BIGINT,
    numero             INTEGER      CHECK (numero > 0),
    orden_importacion  INTEGER      CHECK (orden_importacion > 0),
    titulo             VARCHAR(150) NOT NULL,
    contenido          TEXT         NOT NULL,
    palabras           INTEGER      CHECK (palabras >= 0),
    comentarios_activos BOOLEAN     NOT NULL DEFAULT TRUE,
    estado             VARCHAR(10)  NOT NULL DEFAULT 'borrador'
                       CHECK (estado IN ('borrador', 'publicado', 'retirado')),
    publicado_en       TIMESTAMPTZ,
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_capitulo_numero_si_publicado
        CHECK (estado = 'borrador' OR (numero IS NOT NULL AND publicado_en IS NOT NULL)),
    CONSTRAINT ux_capitulo_obra_numero UNIQUE (obra_id, numero),
    CONSTRAINT ux_capitulo_id_obra UNIQUE (id, obra_id),
    CONSTRAINT fk_capitulo_importacion
        FOREIGN KEY (importacion_id, obra_id)
        REFERENCES importacion_pdf (id, obra_id)
);

CREATE INDEX ix_capitulo_obra_estado ON capitulo (obra_id, estado, numero);
CREATE INDEX ix_capitulo_importacion ON capitulo (importacion_id) WHERE importacion_id IS NOT NULL;

