    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reportante_id        BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    tipo_objetivo        VARCHAR(10)  NOT NULL
                         CHECK (tipo_objetivo IN ('comentario', 'capitulo', 'obra', 'usuario')),
    comentario_id        BIGINT       REFERENCES comentario (id) ON DELETE CASCADE,
    capitulo_id          BIGINT       REFERENCES capitulo (id) ON DELETE CASCADE,
    obra_id              BIGINT       REFERENCES obra (id) ON DELETE CASCADE,
    usuario_reportado_id BIGINT       REFERENCES usuario (id) ON DELETE CASCADE,
    motivo               VARCHAR(25)  NOT NULL
                         CHECK (motivo IN ('spam', 'acoso', 'contenido_inapropiado', 'plagio', 'otro')),
    descripcion          TEXT,
    estado               VARCHAR(12)  NOT NULL DEFAULT 'pendiente'
                         CHECK (estado IN ('pendiente', 'en_revision', 'resuelto', 'descartado')),
    moderador_id         BIGINT       REFERENCES usuario (id),
    resolucion           TEXT,
