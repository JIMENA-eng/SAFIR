CREATE FUNCTION fn_obra_validar_autor() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM usuario_rol ur
        JOIN rol r ON r.id = ur.rol_id
        WHERE ur.usuario_id = NEW.autor_id AND r.nombre = 'autor'
    ) THEN
        RAISE EXCEPTION 'El usuario % no tiene rol autor', NEW.autor_id;
    END IF;
    IF NEW.estado = 'publicada' AND NEW.publicada_en IS NULL THEN
        NEW.publicada_en := now();
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_obra_validar_autor
    BEFORE INSERT OR UPDATE OF autor_id, estado ON obra
    FOR EACH ROW EXECUTE FUNCTION fn_obra_validar_autor();

CREATE FUNCTION fn_obra_crear_estadistica() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO obra_estadistica (obra_id) VALUES (NEW.id);
    RETURN NULL;
END $$;

CREATE TRIGGER trg_obra_estadistica
    AFTER INSERT ON obra
    FOR EACH ROW EXECUTE FUNCTION fn_obra_crear_estadistica();

CREATE FUNCTION fn_capitulo_antes() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'publicado' AND NEW.publicado_en IS NULL THEN
        NEW.publicado_en := now();
    END IF;
    RETURN NEW;
END $$;

