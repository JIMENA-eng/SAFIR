CREATE FUNCTION publicar_importacion(p_importacion_id BIGINT) RETURNS INTEGER
LANGUAGE plpgsql AS $$
DECLARE
    v_obra_id  BIGINT;
    v_estado   VARCHAR(12);
    v_base     INTEGER;
    v_total    INTEGER;
BEGIN
    SELECT obra_id, estado INTO v_obra_id, v_estado
    FROM importacion_pdf
    WHERE id = p_importacion_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La importación % no existe', p_importacion_id;
    END IF;
    IF v_estado <> 'en_revision' THEN
        RAISE EXCEPTION 'La importación % no está en revisión', p_importacion_id;
    END IF;

    SELECT COALESCE(MAX(numero), 0) INTO v_base FROM capitulo WHERE obra_id = v_obra_id;

    WITH ordenados AS (
        SELECT id, ROW_NUMBER() OVER (ORDER BY orden_importacion, id) AS rn
        FROM capitulo
        WHERE importacion_id = p_importacion_id AND estado = 'borrador'
    )
    UPDATE capitulo c
    SET numero = v_base + o.rn,
        estado = 'publicado',
        publicado_en = now()
    FROM ordenados o
    WHERE c.id = o.id;

    GET DIAGNOSTICS v_total = ROW_COUNT;

    IF v_total = 0 THEN
        RAISE EXCEPTION 'La importación % no tiene capítulos por publicar', p_importacion_id;
    END IF;

    UPDATE importacion_pdf
    SET estado = 'confirmada',
        resuelto_en = now(),
        archivo_ruta = NULL
    WHERE id = p_importacion_id;

    RETURN v_total;
END $$;

CREATE FUNCTION continuar_lectura(p_usuario_id BIGINT, p_obra_id BIGINT)
RETURNS TABLE (capitulo_id BIGINT, numero INTEGER, titulo VARCHAR, posicion NUMERIC)
LANGUAGE sql STABLE AS $$
    WITH p AS (
        SELECT pl.capitulo_id AS cap_id, pl.posicion AS pos, c.numero AS num
        FROM progreso_lectura pl
        JOIN capitulo c ON c.id = pl.capitulo_id
        WHERE pl.usuario_id = p_usuario_id AND pl.obra_id = p_obra_id
    )
    SELECT c.id, c.numero, c.titulo,
           CASE WHEN c.id = (SELECT cap_id FROM p) THEN (SELECT pos FROM p) ELSE 0::NUMERIC END
    FROM capitulo c
    WHERE c.obra_id = p_obra_id AND c.estado = 'publicado'
    ORDER BY abs(c.numero - COALESCE((SELECT num FROM p), 1)), c.numero
    LIMIT 1;
$$;

CREATE VIEW v_catalogo_obras AS
SELECT  o.id,
        o.titulo,
        o.descripcion,
        o.portada_ruta,
        g.nombre          AS genero,
        u.nombre_publico  AS autor,
        o.clasificacion,
        o.avance,
        o.publicada_en,
        e.promedio,
        e.total_valoraciones,
        e.total_lecturas,
        e.total_seguidores,
        (SELECT COUNT(*) FROM capitulo c
         WHERE c.obra_id = o.id AND c.estado = 'publicado') AS capitulos_publicados,
        ARRAY(SELECT t.nombre FROM obra_etiqueta oe
              JOIN etiqueta t ON t.id = oe.etiqueta_id
              WHERE oe.obra_id = o.id ORDER BY t.nombre)     AS etiquetas
FROM    obra o
JOIN    genero g           ON g.id = o.genero_id
JOIN    usuario u          ON u.id = o.autor_id
JOIN    obra_estadistica e ON e.obra_id = o.id
WHERE   o.estado = 'publicada';

CREATE VIEW v_panel_autor AS
SELECT  o.autor_id,
        o.id AS obra_id,
        o.titulo,
        o.estado,
        o.avance,
        COUNT(c.id) FILTER (WHERE c.estado = 'publicado') AS capitulos_publicados,
        COUNT(c.id) FILTER (WHERE c.estado = 'borrador')  AS capitulos_borrador,
        e.total_lecturas,
        e.promedio,
        e.total_seguidores
FROM    obra o
JOIN    obra_estadistica e ON e.obra_id = o.id
LEFT JOIN capitulo c       ON c.obra_id = o.id
GROUP BY o.id, e.total_lecturas, e.promedio, e.total_seguidores;

