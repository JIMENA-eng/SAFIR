DO $$
DECLARE
    v_nombre TEXT;
BEGIN
    SELECT conname INTO v_nombre
    FROM pg_constraint
    WHERE conrelid = 'compra_capitulo'::regclass
      AND contype = 'f'
      AND confrelid = 'capitulo'::regclass;

    IF v_nombre IS NOT NULL THEN
        EXECUTE format('ALTER TABLE compra_capitulo DROP CONSTRAINT %I', v_nombre);
    END IF;
END $$;

ALTER TABLE compra_capitulo
    ADD CONSTRAINT compra_capitulo_capitulo_id_fkey
    FOREIGN KEY (capitulo_id) REFERENCES capitulo (id) ON DELETE SET NULL;

-- 2. Al marcar una cuenta como eliminada se borran todas sus obras. Por las cascadas
--    del esquema desaparecen también capítulos, comentarios, valoraciones, avances de
--    lectura, bibliotecas, seguidores y notificaciones de esas obras. Los regalos
--    recibidos se conservan (regalo.obra_id pasa a NULL) y el libro de monedas no se toca.
CREATE FUNCTION fn_usuario_eliminado() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM obra WHERE autor_id = NEW.id;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_usuario_eliminado
    AFTER UPDATE OF estado_cuenta ON usuario
    FOR EACH ROW
    WHEN (NEW.estado_cuenta = 'eliminada' AND OLD.estado_cuenta IS DISTINCT FROM 'eliminada')
    EXECUTE FUNCTION fn_usuario_eliminado();

COMMIT;

