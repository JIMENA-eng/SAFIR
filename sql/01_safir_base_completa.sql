CREATE FUNCTION resolver_retiro(p_retiro_id BIGINT, p_moderador BIGINT, p_aprobar BOOLEAN,
                                p_referencia_pago VARCHAR DEFAULT NULL,
                                p_motivo VARCHAR DEFAULT NULL)
RETURNS VARCHAR
LANGUAGE plpgsql AS $$
DECLARE
    v retiro%ROWTYPE;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id = ur.rol_id
                   WHERE ur.usuario_id = p_moderador AND r.nombre IN ('administrador', 'moderador')) THEN
        RAISE EXCEPTION 'El usuario % no puede resolver retiros', p_moderador;
    END IF;

    SELECT * INTO v FROM retiro WHERE id = p_retiro_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El retiro % no existe', p_retiro_id; END IF;
    IF v.estado <> 'pendiente' THEN RAISE EXCEPTION 'El retiro % ya fue resuelto', p_retiro_id; END IF;

    IF p_aprobar THEN
        UPDATE retiro
        SET estado = 'pagado', referencia_pago = p_referencia_pago,
            resuelto_en = now(), resuelto_por = p_moderador
        WHERE id = p_retiro_id;

        INSERT INTO notificacion (usuario_id, tipo, mensaje)
        VALUES (v.autor_id, 'sistema', 'Tu retiro fue pagado');
        RETURN 'pagado';
    END IF;

    IF p_motivo IS NULL OR length(btrim(p_motivo)) = 0 THEN
        RAISE EXCEPTION 'Debes indicar el motivo del rechazo';
    END IF;

    UPDATE retiro
    SET estado = 'rechazado', motivo_rechazo = p_motivo,
        resuelto_en = now(), resuelto_por = p_moderador
    WHERE id = p_retiro_id;

    -- Se devuelven TODAS las monedas solicitadas (incluida la parte de la plataforma)
    PERFORM mover_monedas(v.autor_id, v.monedas_solicitadas, 'reembolso_retiro', 'retiro', v.id);

    INSERT INTO notificacion (usuario_id, tipo, mensaje)
    VALUES (v.autor_id, 'sistema', 'Tu retiro fue rechazado y tus monedas fueron devueltas');
    RETURN 'rechazado';
END $$;

