CREATE FUNCTION fn_valoracion_estadistica() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE obra_estadistica
        SET total_valoraciones = total_valoraciones + 1,
            suma_puntaje = suma_puntaje + NEW.puntaje
        WHERE obra_id = NEW.obra_id;
    ELSIF TG_OP = 'UPDATE' THEN
        UPDATE obra_estadistica
        SET suma_puntaje = suma_puntaje - OLD.puntaje + NEW.puntaje
        WHERE obra_id = NEW.obra_id;
    ELSE
        UPDATE obra_estadistica
        SET total_valoraciones = total_valoraciones - 1,
            suma_puntaje = suma_puntaje - OLD.puntaje
        WHERE obra_id = OLD.obra_id;
    END IF;
    RETURN NULL;
END $$;

