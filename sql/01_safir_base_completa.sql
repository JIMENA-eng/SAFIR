BEGIN;

-- 1. Las compras de capítulos son registros contables de dinero ya movido:
--    se conservan aunque el capítulo desaparezca (capitulo_id pasa a NULL).
--    Sin este cambio, borrar una obra con capítulos vendidos falla por llave foránea.
