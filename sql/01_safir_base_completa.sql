        (tipo_objetivo = 'comentario' AND comentario_id IS NOT NULL) OR
        (tipo_objetivo = 'capitulo'   AND capitulo_id IS NOT NULL) OR
        (tipo_objetivo = 'obra'       AND obra_id IS NOT NULL) OR
        (tipo_objetivo = 'usuario'    AND usuario_reportado_id IS NOT NULL)
