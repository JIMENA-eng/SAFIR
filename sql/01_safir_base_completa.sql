-- Mueve monedas de una billetera y deja el rastro en el libro. Bloquea la fila.
CREATE FUNCTION mover_monedas(p_usuario BIGINT, p_monedas BIGINT, p_tipo VARCHAR,
                              p_ref_tipo VARCHAR DEFAULT NULL, p_ref_id BIGINT DEFAULT NULL)
RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v_saldo BIGINT;
BEGIN
    SELECT saldo_monedas INTO v_saldo FROM billetera WHERE usuario_id = p_usuario FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El usuario % no tiene billetera', p_usuario;
    END IF;
    IF v_saldo + p_monedas < 0 THEN
        RAISE EXCEPTION 'Saldo insuficiente (tiene %, necesita %)', v_saldo, -p_monedas;
    END IF;

    v_saldo := v_saldo + p_monedas;
    UPDATE billetera SET saldo_monedas = v_saldo WHERE usuario_id = p_usuario;

    INSERT INTO movimiento_moneda (usuario_id, tipo, monedas, saldo_posterior, referencia_tipo, referencia_id)
    VALUES (p_usuario, p_tipo, p_monedas, v_saldo, p_ref_tipo, p_ref_id);

    RETURN v_saldo;
END $$;

-- Descuento vigente (0 si no tiene)
CREATE FUNCTION descuento_vigente(p_usuario BIGINT) RETURNS SMALLINT
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(MAX(porcentaje), 0)::SMALLINT
    FROM promocion_usuario
    WHERE usuario_id = p_usuario AND now() >= inicia_en AND now() < vence_en;
$$;

-- Al registrarse: perfil vacío, billetera, 1000 monedas y 20 % por 7 días
CREATE FUNCTION fn_usuario_bienvenida() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO perfil_usuario (usuario_id) VALUES (NEW.id) ON CONFLICT DO NOTHING;
    INSERT INTO billetera (usuario_id) VALUES (NEW.id);

    PERFORM mover_monedas(NEW.id, cfg('bono_bienvenida_monedas')::BIGINT, 'bono_bienvenida');

    INSERT INTO promocion_usuario (usuario_id, tipo, porcentaje, vence_en)
    VALUES (NEW.id, 'bienvenida', cfg('descuento_bienvenida_pct')::SMALLINT,
            now() + make_interval(days => cfg('descuento_bienvenida_dias')::INT));
    RETURN NULL;
END $$;

CREATE TRIGGER trg_usuario_bienvenida
    AFTER INSERT ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_usuario_bienvenida();

-- Al recibir el rol autor: crear su nivel 1
CREATE FUNCTION fn_usuario_rol_autor() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM rol WHERE id = NEW.rol_id AND nombre = 'autor') THEN
        INSERT INTO autor_nivel (autor_id) VALUES (NEW.usuario_id) ON CONFLICT DO NOTHING;
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_usuario_rol_autor
    AFTER INSERT ON usuario_rol
    FOR EACH ROW EXECUTE FUNCTION fn_usuario_rol_autor();

-- Usuarios que ya existían: billetera en 0 (sin bono retroactivo) y nivel de autores
