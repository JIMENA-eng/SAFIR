    usuario_id         BIGINT        NOT NULL REFERENCES usuario (id),
    monedas            BIGINT        NOT NULL CHECK (monedas > 0),
    valor_bruto_usd    NUMERIC(10,2) NOT NULL CHECK (valor_bruto_usd >= 0),
    comision_pct       NUMERIC(5,2)  NOT NULL,
    comision_usd       NUMERIC(10,2) NOT NULL CHECK (comision_usd >= 0),
    monto_usd          NUMERIC(10,2) NOT NULL CHECK (monto_usd >= 0),
    monedas_perdidas   BIGINT        NOT NULL DEFAULT 0 CHECK (monedas_perdidas >= 0),
    estado             VARCHAR(12)   NOT NULL DEFAULT 'pendiente'
                       CHECK (estado IN ('pendiente', 'pagado')),
    referencia_pago    VARCHAR(100),
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resuelto_en        TIMESTAMPTZ,
