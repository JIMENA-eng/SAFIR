CREATE INDEX ix_reembolso_estado ON reembolso_cuenta (estado, creado_en);

-- Se reembolsa solo lo que el usuario COMPRÓ con dinero (hasta el saldo que tenga),
-- valorado al precio promedio realmente pagado por moneda, menos 5 %.
-- Las monedas del bono de bienvenida y las ganadas como autor no se reembolsan:
-- si las hay, hay que confirmarlo con p_acepta_perder = TRUE (el autor debería retirar antes).
CREATE FUNCTION eliminar_cuenta(p_usuario BIGINT, p_acepta_perder BOOLEAN DEFAULT FALSE)
RETURNS NUMERIC
LANGUAGE plpgsql AS $$
DECLARE
    v_estado     VARCHAR(12);
    v_saldo      BIGINT;
    v_compradas  BIGINT;
    v_pagado_usd NUMERIC;
    v_reembolso  BIGINT;
    v_perdidas   BIGINT;
    v_bruto      NUMERIC(10,2) := 0;
    v_pct        NUMERIC := cfg('comision_reembolso_pct');
    v_com        NUMERIC(10,2) := 0;
    v_monto      NUMERIC(10,2) := 0;
BEGIN
    SELECT estado_cuenta INTO v_estado FROM usuario WHERE id = p_usuario FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El usuario % no existe', p_usuario; END IF;
    IF v_estado = 'eliminada' THEN RAISE EXCEPTION 'La cuenta ya está eliminada'; END IF;

    IF EXISTS (SELECT 1 FROM retiro WHERE autor_id = p_usuario AND estado = 'pendiente') THEN
        RAISE EXCEPTION 'Tienes un retiro pendiente; espera a que se resuelva';
    END IF;

    SELECT saldo_monedas INTO v_saldo FROM billetera WHERE usuario_id = p_usuario FOR UPDATE;

    SELECT COALESCE(SUM(monedas), 0), COALESCE(SUM(precio_pagado_usd), 0)
    INTO v_compradas, v_pagado_usd
    FROM compra_paquete
    WHERE usuario_id = p_usuario AND estado = 'pagada';

    v_reembolso := LEAST(v_saldo, v_compradas);
    v_perdidas  := v_saldo - v_reembolso;

    IF v_perdidas > 0 AND NOT p_acepta_perder THEN
        RAISE EXCEPTION 'Tienes % monedas que no son reembolsables (bono o ganancias). Confirma que aceptas perderlas.',
                        v_perdidas;
    END IF;

    IF v_reembolso > 0 THEN
        v_bruto := ROUND(v_reembolso * (v_pagado_usd / v_compradas), 2);
        v_com   := ROUND(v_bruto * v_pct / 100.0, 2);
        v_monto := v_bruto - v_com;

        INSERT INTO reembolso_cuenta (usuario_id, monedas, valor_bruto_usd, comision_pct,
                                      comision_usd, monto_usd, monedas_perdidas)
        VALUES (p_usuario, v_reembolso, v_bruto, v_pct, v_com, v_monto, v_perdidas);
    END IF;

    IF v_saldo > 0 THEN
        PERFORM mover_monedas(p_usuario, -v_saldo, 'reembolso_cuenta', 'usuario', p_usuario);
    END IF;

    UPDATE usuario SET estado_cuenta = 'eliminada' WHERE id = p_usuario;
    UPDATE sesion_token SET revocado_en = now() WHERE usuario_id = p_usuario AND revocado_en IS NULL;

    RETURN v_monto;   -- dólares que se le devolverán
END $$;

COMMIT;


