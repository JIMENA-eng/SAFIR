-- 10.1 Crear la compra de un paquete (queda pendiente hasta que la pasarela confirme)
CREATE FUNCTION crear_compra_paquete(p_usuario BIGINT, p_paquete SMALLINT,
                                     p_pasarela VARCHAR DEFAULT NULL,
                                     p_referencia VARCHAR DEFAULT NULL)
RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v_paq   paquete_monedas%ROWTYPE;
    v_desc  SMALLINT := descuento_vigente(p_usuario);
    v_pagar NUMERIC(8,2);
    v_pct   NUMERIC := cfg('comision_compra_pct');
    v_id    BIGINT;
BEGIN
    SELECT * INTO v_paq FROM paquete_monedas WHERE id = p_paquete AND activo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Paquete % no disponible', p_paquete;
    END IF;

    v_pagar := ROUND(v_paq.precio_usd * (100 - v_desc) / 100.0, 2);

    INSERT INTO compra_paquete (usuario_id, paquete_id, monedas, precio_lista_usd, descuento_pct,
                                precio_pagado_usd, comision_pct, comision_usd, pasarela, referencia_pago)
    VALUES (p_usuario, v_paq.id, v_paq.monedas, v_paq.precio_usd, v_desc,
            v_pagar, v_pct, ROUND(v_pagar * v_pct / 100.0, 2), p_pasarela, p_referencia)
    RETURNING id INTO v_id;
    RETURN v_id;
END $$;

-- 10.2 La pasarela confirmó el pago: se acreditan las monedas
CREATE FUNCTION confirmar_compra_paquete(p_compra_id BIGINT) RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v compra_paquete%ROWTYPE;
BEGIN
    SELECT * INTO v FROM compra_paquete WHERE id = p_compra_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'La compra % no existe', p_compra_id; END IF;
    IF v.estado <> 'pendiente' THEN RAISE EXCEPTION 'La compra % no está pendiente', p_compra_id; END IF;

    UPDATE compra_paquete SET estado = 'pagada', pagado_en = now() WHERE id = p_compra_id;
    RETURN mover_monedas(v.usuario_id, v.monedas, 'compra_paquete', 'compra_paquete', v.id);
END $$;

-- 10.3 Regalo al autor: el autor recibe 88 %, la plataforma 12 %
CREATE FUNCTION enviar_regalo(p_remitente BIGINT, p_autor BIGINT, p_monedas INTEGER,
                              p_obra BIGINT DEFAULT NULL, p_mensaje VARCHAR DEFAULT NULL)
RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v_pct   NUMERIC := cfg('comision_regalo_pct');
    v_com   INTEGER;
    v_neto  INTEGER;
    v_id    BIGINT;
BEGIN
    IF p_monedas IS NULL OR p_monedas <= 0 THEN RAISE EXCEPTION 'Cantidad inválida'; END IF;
    IF p_remitente = p_autor THEN RAISE EXCEPTION 'No puedes regalarte a ti mismo'; END IF;
    IF NOT EXISTS (SELECT 1 FROM autor_nivel WHERE autor_id = p_autor) THEN
        RAISE EXCEPTION 'El usuario % no es autor', p_autor;
    END IF;

    v_com  := ROUND(p_monedas * v_pct / 100.0);
    v_neto := p_monedas - v_com;

    INSERT INTO regalo (remitente_id, autor_id, obra_id, monedas_enviadas, comision_pct,
                        monedas_comision, monedas_autor, mensaje)
    VALUES (p_remitente, p_autor, p_obra, p_monedas, v_pct, v_com, v_neto, p_mensaje)
    RETURNING id INTO v_id;

    PERFORM mover_monedas(p_remitente, -p_monedas, 'regalo_enviado', 'regalo', v_id);
    PERFORM mover_monedas(p_autor,      v_neto,    'regalo_recibido', 'regalo', v_id);
    UPDATE billetera SET total_recibido = total_recibido + v_neto WHERE usuario_id = p_autor;
    RETURN v_id;
END $$;

-- 10.4 Comprar un capítulo (5 monedas; con descuento de bienvenida si aplica)
CREATE FUNCTION comprar_capitulo(p_usuario BIGINT, p_capitulo BIGINT) RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v_precio SMALLINT;
    v_autor  BIGINT;
    v_desc   SMALLINT := descuento_vigente(p_usuario);
    v_pct    NUMERIC  := cfg('comision_capitulo_pct');
    v_pagar  INTEGER;
    v_com    INTEGER;
    v_neto   INTEGER;
    v_id     BIGINT;
BEGIN
    SELECT c.precio_monedas, o.autor_id INTO v_precio, v_autor
    FROM capitulo c JOIN obra o ON o.id = c.obra_id
    WHERE c.id = p_capitulo AND c.estado = 'publicado' AND o.estado = 'publicada';
    IF NOT FOUND THEN RAISE EXCEPTION 'Capítulo % no disponible', p_capitulo; END IF;
    IF v_autor = p_usuario THEN RAISE EXCEPTION 'Es tu propio capítulo'; END IF;
    IF EXISTS (SELECT 1 FROM compra_capitulo WHERE usuario_id = p_usuario AND capitulo_id = p_capitulo) THEN
        RAISE EXCEPTION 'Ya compraste este capítulo';
    END IF;

    v_pagar := CEIL(v_precio * (100 - v_desc) / 100.0);
    v_com   := ROUND(v_pagar * v_pct / 100.0);
    v_neto  := v_pagar - v_com;

    INSERT INTO compra_capitulo (usuario_id, capitulo_id, precio_monedas, descuento_pct,
                                 monedas_pagadas, comision_pct, monedas_comision, monedas_autor)
    VALUES (p_usuario, p_capitulo, v_precio, v_desc, v_pagar, v_pct, v_com, v_neto)
    RETURNING id INTO v_id;

    IF v_pagar > 0 THEN
        PERFORM mover_monedas(p_usuario, -v_pagar, 'compra_capitulo', 'compra_capitulo', v_id);
        IF v_neto > 0 THEN
            PERFORM mover_monedas(v_autor, v_neto, 'venta_capitulo', 'compra_capitulo', v_id);
            UPDATE billetera SET total_recibido = total_recibido + v_neto WHERE usuario_id = v_autor;
        END IF;
    END IF;
    RETURN v_id;
END $$;

-- ¿Puede este usuario leer el capítulo?
CREATE FUNCTION puede_leer_capitulo(p_usuario BIGINT, p_capitulo BIGINT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
        FROM capitulo c JOIN obra o ON o.id = c.obra_id
        WHERE c.id = p_capitulo
          AND (c.precio_monedas = 0
               OR o.autor_id = p_usuario
               OR EXISTS (SELECT 1 FROM compra_capitulo cc
                          WHERE cc.usuario_id = p_usuario AND cc.capitulo_id = c.id))
    );
$$;

-- 10.5 Comprar un nivel (10 000 monedas por nivel)
CREATE FUNCTION comprar_nivel(p_autor BIGINT) RETURNS SMALLINT
LANGUAGE plpgsql AS $$
DECLARE
    v_nivel SMALLINT;
    v_costo INTEGER := cfg('costo_nivel_monedas')::INTEGER;
BEGIN
    SELECT nivel INTO v_nivel FROM autor_nivel WHERE autor_id = p_autor FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El usuario % no es autor', p_autor; END IF;
    IF v_nivel >= cfg('nivel_maximo') THEN RAISE EXCEPTION 'Ya está en el nivel máximo'; END IF;

    PERFORM mover_monedas(p_autor, -v_costo, 'compra_nivel', 'autor_nivel', p_autor);
    UPDATE autor_nivel SET nivel = v_nivel + 1 WHERE autor_id = p_autor;
    INSERT INTO compra_nivel (autor_id, nivel_anterior, nivel_nuevo, monedas)
    VALUES (p_autor, v_nivel, v_nivel + 1, v_costo);
    RETURN v_nivel + 1;
END $$;

-- 10.6 Solicitar retiro: saldo >= 100 000 y nivel >= 3; 80 % autor / 20 % plataforma
CREATE FUNCTION solicitar_retiro(p_autor BIGINT, p_monedas BIGINT, p_metodo VARCHAR) RETURNS BIGINT
LANGUAGE plpgsql AS $$
DECLARE
    v_nivel  SMALLINT;
    v_saldo  BIGINT;
    v_pct    NUMERIC := cfg('retiro_comision_pct');
    v_plat   BIGINT;
    v_autor  BIGINT;
    v_valor  NUMERIC := cfg('valor_moneda_retiro_usd');
    v_id     BIGINT;
BEGIN
    SELECT nivel INTO v_nivel FROM autor_nivel WHERE autor_id = p_autor;
    IF NOT FOUND THEN RAISE EXCEPTION 'El usuario % no es autor', p_autor; END IF;
    IF v_nivel < cfg('retiro_nivel_minimo') THEN
        RAISE EXCEPTION 'Necesitas nivel % para retirar (tienes %)', cfg('retiro_nivel_minimo'), v_nivel;
    END IF;

    SELECT saldo_monedas INTO v_saldo FROM billetera WHERE usuario_id = p_autor FOR UPDATE;
    IF v_saldo < cfg('retiro_minimo_monedas') THEN
        RAISE EXCEPTION 'Necesitas al menos % monedas para retirar (tienes %)',
                        cfg('retiro_minimo_monedas'), v_saldo;
    END IF;
    IF p_monedas <= 0 OR p_monedas > v_saldo THEN RAISE EXCEPTION 'Monto de retiro inválido'; END IF;

    v_plat  := ROUND(p_monedas * v_pct / 100.0);
    v_autor := p_monedas - v_plat;

    INSERT INTO retiro (autor_id, monedas_solicitadas, comision_pct, monedas_plataforma, monedas_autor,
                        valor_moneda_usd, monto_usd, metodo_pago)
    VALUES (p_autor, p_monedas, v_pct, v_plat, v_autor, v_valor, ROUND(v_autor * v_valor, 2), p_metodo)
    RETURNING id INTO v_id;

    PERFORM mover_monedas(p_autor, -p_monedas, 'retiro', 'retiro', v_id);
    RETURN v_id;
END $$;

